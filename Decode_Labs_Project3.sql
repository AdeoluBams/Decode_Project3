-- Yearly revenue
SELECT
	EXTRACT(YEAR FROM "Date") AS year_,
	SUM("TotalPrice") AS total_amount
FROM public."Decode_Labs"
GROUP BY year_
ORDER BY year_ ASC;

-- Monthly and yearly revenue trend
SELECT
	EXTRACT(YEAR FROM "Date") AS year_,
	EXTRACT(MONTH FROM "Date") AS month_,
	SUM("TotalPrice") AS total_amount
FROM public."Decode_Labs"
GROUP BY year_,month_
ORDER BY year_,month_ ASC;

-- Yearly Growth rate
WITH yearly_revenue AS(
	SELECT
		EXTRACT(YEAR FROM "Date") AS year_,
		SUM("TotalPrice") AS total_amount
	FROM public."Decode_Labs"
	GROUP BY year_
	ORDER BY year_ ASC
),
Preceding_rev_calc AS(
	SELECT
		year_,
		total_amount,
		LAG(total_amount) OVER(ORDER BY year_) AS prev_revenue
	FROM yearly_revenue
)
SELECT
	year_,
	total_amount,
	ROUND(
		(total_amount - prev_revenue) * 100.0 / prev_revenue,2) revenue_growth_perc
FROM Preceding_rev_calc

-- Month_year growth
WITH year_month_revenue AS(
	SELECT
		EXTRACT(YEAR FROM "Date") AS year_,
		EXTRACT(MONTH FROM "Date") AS month_,
		SUM("TotalPrice") AS total_amount
	FROM public."Decode_Labs"
	GROUP BY year_, month_
	ORDER BY year_,month_ ASC
),
Preceding_rev_calc AS(
	SELECT
		year_,
		month_,
		total_amount,
		LAG(total_amount) OVER(ORDER BY year_, month_) AS prev_revenue
	FROM year_month_revenue
)
SELECT
	year_,
	month_,
	total_amount,
	ROUND(
		(total_amount - prev_revenue) * 100.0 / prev_revenue,2) revenue_growth_perc
FROM Preceding_rev_calc
GROUP BY year_, month_, total_amount, prev_revenue
ORDER BY year_, month_;



-- Products that dominated each year in terms of revenue
SELECT
	EXTRACT(YEAR FROM "Date") AS year_,
	("Product") AS product,
	SUM("TotalPrice") AS total_amount
FROM public."Decode_Labs"
GROUP BY year_, product
ORDER BY year_ ASC, total_amount DESC;

