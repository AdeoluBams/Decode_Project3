SELECT * 
FROM public."Decode_Labs";

-- Total Quantity sold
SELECT 
	SUM("Quantity") AS total_quantity
FROM public."Decode_Labs";

-- Total Number of orders
SELECT 
	COUNT("OrderID") AS total_orders
FROM public."Decode_Labs";

-- Average Order Value
WITH average_order_calc AS(
	SELECT
		SUM("TotalPrice") AS total_amount,
		COUNT("OrderID") AS total_orders
	FROM public."Decode_Labs"
)
SELECT
	ROUND(
		(total_amount / total_orders),0) AS average_order_value
FROM average_order_calc;

-- Most sold product
SELECT 
	"Product",
	COUNT("Product") AS frequency
FROM public."Decode_Labs"
GROUP BY "Product" 
ORDER BY frequency DESC;

-- Quantity sales and total amount  by Product
SELECT
	"Product",
	SUM("Quantity") AS total_quantity,
	SUM("TotalPrice") AS total_amount
FROM public."Decode_Labs"
GROUP BY "Product" 
ORDER BY total_amount DESC;

-- Total amount generated by referral source / Customer Acq channel
SELECT
	"ReferralSource",
	SUM("TotalPrice") AS total_amount
FROM public."Decode_Labs"
